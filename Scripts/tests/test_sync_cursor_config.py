"""Tests for Scripts/sync_cursor_config.py (Cursor copies of the Claude Code agent config).

Conversion and drift detection run on throwaway repos in a temp dir. Nothing here compares the
real .cursor/ with the Claude originals: that check is manual (py Scripts/sync_cursor_config.py
--check, which CLAUDE.md asks for after any change to .claude/skills/ or .mcp.json).
TestCursorMcpRegistration pins the real .cursor/mcp.json entry, as test_mordecai_play_mcp.py
pins .mcp.json.
"""

import contextlib
import io
import json
import os
import sys
import tempfile
import unittest

SCRIPTS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJECT_ROOT = os.path.dirname(SCRIPTS)
if SCRIPTS not in sys.path:
    sys.path.insert(0, SCRIPTS)

import sync_cursor_config as scc  # noqa: E402

SKILL = ("---\n"
         "name: alpha\n"
         "description: >\n"
         "  Alpha skill. Use when: (1) testing the sync,\n"
         "  (2) checking the frontmatter.\n"
         "---\n"
         "\n"
         "# Alpha\n"
         "\n"
         "Read `references/notes.md`. ADD new lessons here.\n")
NOTES = "# Notes\n\nSome reference text \u2014 with an em dash.\n"
MCP = {"mcpServers": {"play": {"type": "stdio", "command": "py",
                               "args": ["-X", "utf8", "Scripts/server.py"],
                               "env": {"PYTHONUNBUFFERED": "1"}}}}


def write(root, rel, text, newline="\n"):
    path = os.path.join(root, *rel.split("/"))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(text.replace("\n", newline))
    return path


def read(root, rel):
    with open(os.path.join(root, *rel.split("/")), "rb") as f:
        return f.read()


class TestSkillConversion(unittest.TestCase):
    def test_keeps_frontmatter_and_body_and_adds_metadata_and_banner(self):
        out = scc.cursor_skill_md(SKILL, "alpha")
        head, body = out.split("\n---\n", 1)
        self.assertTrue(head.startswith("---\nname: alpha\ndescription: >\n  Alpha skill."))
        self.assertIn("\nmetadata:\n  generated-from: .claude/skills/alpha/SKILL.md\n"
                      "  generated-by: py Scripts/sync_cursor_config.py", head)
        self.assertTrue(body.startswith("\n> Generated by `py Scripts/sync_cursor_config.py` "
                                        "from `.claude/skills/alpha/SKILL.md`"))
        self.assertTrue(out.endswith(SKILL.split("---\n", 2)[2]))
        self.assertEqual(scc.top_level_keys(scc.split_frontmatter(out, "x")[0])["name"], "alpha")

    def test_crlf_source_stays_crlf(self):
        out = scc.cursor_skill_md(SKILL.replace("\n", "\r\n"), "alpha")
        self.assertNotIn("\n", out.replace("\r\n", ""))

    def test_body_without_a_blank_line_still_gets_one_after_the_banner(self):
        out = scc.cursor_skill_md("---\nname: alpha\ndescription: d\n---\n# Alpha\n", "alpha")
        self.assertIn("overwritten.\n\n# Alpha\n", out)

    def test_unconvertible_sources_are_refused(self):
        cases = {
            "no frontmatter": "# Alpha\n",
            "unclosed": "---\nname: alpha\ndescription: d\n",
            "name mismatch": "---\nname: beta\ndescription: d\n---\nbody\n",
            "no description": "---\nname: alpha\n---\nbody\n",
            "metadata": "---\nname: alpha\ndescription: d\nmetadata:\n  a: b\n---\nbody\n",
        }
        for label, text in cases.items():
            with self.subTest(label), self.assertRaises(scc.SyncError):
                scc.cursor_skill_md(text, "alpha")

    def test_invalid_cursor_name_is_refused(self):
        with self.assertRaises(scc.SyncError):
            scc.cursor_skill_md("---\nname: Alpha_1\ndescription: d\n---\nbody\n", "Alpha_1")


class TestSyncTree(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory(ignore_cleanup_errors=True)
        self.addCleanup(self._tmp.cleanup)
        self.root = self._tmp.name
        write(self.root, ".claude/skills/alpha/SKILL.md", SKILL, "\r\n")
        write(self.root, ".claude/skills/alpha/references/notes.md", NOTES, "\r\n")
        write(self.root, "Scripts/server.py", "print('server')\n")
        write(self.root, ".mcp.json", json.dumps(MCP, indent=2) + "\n", "\r\n")

    def run_main(self, *args):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = scc.main(["--root", self.root, *args])
        return code, out.getvalue()

    def drift(self):
        return [(kind, rel) for kind, rel, _ in scc.find_drift(self.root)]

    def test_check_finds_missing_files_and_sync_writes_them(self):
        code, out = self.run_main("--check")
        self.assertEqual(code, 1, out)
        self.assertIn("missing .cursor/skills/alpha/SKILL.md", out)
        self.assertIn("missing .cursor/mcp.json", out)
        self.assertFalse(os.path.exists(os.path.join(self.root, ".cursor")))
        code, out = self.run_main()
        self.assertEqual(code, 0, out)
        self.assertEqual(read(self.root, ".cursor/skills/alpha/references/notes.md"),
                         read(self.root, ".claude/skills/alpha/references/notes.md"))
        self.assertIn(b"generated-by: py Scripts/sync_cursor_config.py",
                      read(self.root, ".cursor/skills/alpha/SKILL.md"))
        self.assertEqual(self.drift(), [])
        self.assertEqual(self.run_main("--check")[0], 0)

    def test_second_sync_writes_nothing(self):
        self.run_main()
        code, out = self.run_main()
        self.assertEqual(code, 0, out)
        self.assertNotIn("wrote", out)

    def test_stale_and_extra_files_are_reported_then_fixed(self):
        self.run_main()
        write(self.root, ".cursor/skills/alpha/SKILL.md", "hand edit\n")
        write(self.root, ".cursor/skills/alpha/references/old.md", "gone upstream\n")
        self.assertEqual(sorted(self.drift()),
                         [("extra", ".cursor/skills/alpha/references/old.md"),
                          ("stale", ".cursor/skills/alpha/SKILL.md")])
        self.assertEqual(self.run_main()[0], 0)
        self.assertEqual(self.drift(), [])
        self.assertFalse(os.path.exists(
            os.path.join(self.root, ".cursor", "skills", "alpha", "references", "old.md")))

    def test_line_endings_alone_are_not_drift(self):
        self.run_main()
        write(self.root, ".cursor/skills/alpha/references/notes.md", NOTES, "\n")
        self.assertEqual(self.drift(), [])

    def test_removed_source_skill_goes_but_a_cursor_only_skill_stays(self):
        self.run_main()
        write(self.root, ".cursor/skills/cursor-only/SKILL.md",
              "---\nname: cursor-only\ndescription: d\n---\nbody\n")
        for rel in (".claude/skills/alpha/SKILL.md", ".claude/skills/alpha/references/notes.md"):
            os.remove(os.path.join(self.root, *rel.split("/")))
        self.assertEqual(sorted(kind for kind, _ in self.drift()), ["extra", "extra"])
        self.assertEqual(self.run_main()[0], 0)
        self.assertFalse(os.path.exists(os.path.join(self.root, ".cursor", "skills", "alpha")))
        self.assertTrue(os.path.isfile(
            os.path.join(self.root, ".cursor", "skills", "cursor-only", "SKILL.md")))

    def test_mcp_script_paths_become_dot_relative(self):
        self.run_main()
        cfg = json.loads(read(self.root, ".cursor/mcp.json"))
        entry = cfg["mcpServers"]["play"]
        self.assertEqual(entry["args"], ["-X", "utf8", "./Scripts/server.py"])
        self.assertEqual({k: v for k, v in entry.items() if k != "args"},
                         {k: v for k, v in MCP["mcpServers"]["play"].items() if k != "args"})

    def test_mcp_cursor_only_servers_and_formatting_are_kept(self):
        self.run_main()
        cfg = json.loads(read(self.root, ".cursor/mcp.json"))
        cfg["mcpServers"]["cursor-only"] = {"command": "node", "args": ["x.js"]}
        write(self.root, ".cursor/mcp.json", json.dumps(cfg, separators=(",", ":")))
        self.assertEqual(self.drift(), [])
        changed = json.loads(json.dumps(MCP))
        changed["mcpServers"]["play"]["env"]["EXTRA"] = "1"
        write(self.root, ".mcp.json", json.dumps(changed))
        self.assertEqual(self.drift(), [("stale", ".cursor/mcp.json")])
        self.run_main()
        cfg = json.loads(read(self.root, ".cursor/mcp.json"))
        self.assertEqual(cfg["mcpServers"]["play"]["env"]["EXTRA"], "1")
        self.assertIn("cursor-only", cfg["mcpServers"])

    def test_broken_sources_exit_2(self):
        write(self.root, ".mcp.json", "{not json")
        self.assertEqual(self.run_main("--check")[0], 2)
        write(self.root, ".mcp.json", json.dumps(MCP))
        write(self.root, ".claude/skills/alpha/SKILL.md", "---\nname: beta\ndescription: d\n---\n")
        code, out = self.run_main()
        self.assertEqual(code, 2, out)
        self.assertIn("match the folder name", out)
        self.assertFalse(os.path.exists(os.path.join(self.root, ".cursor")))


class TestCursorMcpRegistration(unittest.TestCase):
    def test_cursor_mcp_json_registers_mordecai_play(self):
        with open(os.path.join(PROJECT_ROOT, ".cursor", "mcp.json"), encoding="utf-8") as f:
            entry = json.load(f)["mcpServers"]["mordecai-play"]
        self.assertEqual(entry["type"], "stdio")
        self.assertEqual(entry["command"], "py")
        self.assertEqual(entry["args"], ["-X", "utf8", "./Scripts/mordecai_play_mcp.py"])
        self.assertEqual(entry["env"], {"PYTHONUNBUFFERED": "1"})


if __name__ == "__main__":
    unittest.main()
